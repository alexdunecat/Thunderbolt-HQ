/** Имя силуэта из пути картинки: «…/assets/planes/su27.svg» → «su27». */
export const silhouetteOf = src => /\/([\w-]+)\.(?:svg|webp|png)(?:\?.*)?$/i.exec(String(src ?? ""))?.[1] ?? null;

/**
 * Сопла машины: по силуэту из таблицы, иначе по классу (тяжёлые NPC — четыре гондолы, остальные — спарка в хвосте).
 * null — следа нет (поршневые, вертолёты).
 */
export function enginesOf(src, actor = null) {
  const key = silhouetteOf(src);
  if (key && key in ENGINES) return ENGINES[key] ? { cls: "jet", w: 1, ...ENGINES[key] } : null;
  const g = actor?.system?.grp;
  if (actor?.type === "npc" && g === "heli") return null;
  if (actor?.type === "npc" && ["heavy", "support", "civil"].includes(g)) return { e: [-0.24, -0.13, 0.13, 0.24], y: 0.42, cls: "heavy", w: 1 };
  return { e: [-0.03, 0.03], y: 0.9, cls: "jet", w: 1 };
}

/**
 * Нитки следа за машиной, прошедшей от a к b (центры токена), длиной len и шириной wid (картинка во весь токен, нос по ходу):
 * [{ from, to, nx, ny, off }] — ось нитки на оси машины и смещение off вбок по нормали (nx, ny), чтобы нитки могли сходиться.
 * След начинается чуть позади сопла (пар конденсируется не сразу) и не ближе хвоста машины.
 */
export function contrailLines(a, b, len, wid, eng) {
  const d = Math.hypot(b.x - a.x, b.y - a.y);
  if (d < 2 || !eng?.e?.length) return [];
  const ux = (b.x - a.x) / d, uy = (b.y - a.y) / d, nx = -uy, ny = ux;
  // интерфейсный слой рисуется поверх токенов: нитки начинаются за хвостом, чтобы не лечь поверх крыла и фюзеляжа
  const back = Math.max((eng.y - 0.5) * len + len * (eng.cls === "jet" ? 0.08 : 0.12), len * 0.46);
  const from = { x: a.x - ux * back, y: a.y - uy * back }, to = { x: b.x - ux * back, y: b.y - uy * back };
  return eng.e.map(e => ({ from, to, nx, ny, off: e * wid }));
}
